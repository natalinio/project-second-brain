"""Shared helpers for the KB tooling: paths, schema, frontmatter, folder contract.

Every tools/kb script imports this, so the vocabulary and the folder rules exist in one
place (schema.yaml) and nowhere else.
"""

from __future__ import annotations

import json
import re
import sys
from functools import lru_cache
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
KB_DB = REPO / "metadata" / "kb.duckdb"  # brain index: catalog, registers, graph (rebuildable)
REGISTERS = REPO / "artifacts" / "registers"
ADR_DIR = REPO / "artifacts" / "adr"

GENERATED_MARKER = "<!-- GENERATED by tools/kb"


@lru_cache(maxsize=1)
def schema() -> dict:
    return yaml.safe_load((Path(__file__).parent / "schema.yaml").read_text(encoding="utf-8"))


INV_DB = REPO / schema().get("structured_db", "metadata/inventory.duckdb")  # tabular ground truth
MD_ROOTS = tuple(schema().get("md_roots", ["knowledge", "artifacts", "docs"]))
SKIP_PREFIXES = tuple(schema().get("skip_prefixes", []))


def utf8_stdout() -> None:
    """CLI output uses arrows and dashes; keep a legacy Windows console from choking on them."""
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):
            pass


def register_names() -> list[str]:
    return list(schema()["registers"])


@lru_cache(maxsize=1)
def id_regex() -> re.Pattern:
    """Matches any register id or ADR id, e.g. OP-001, C-012, D-003, ADR-0001."""
    pats = [r["id"] for r in schema()["registers"].values()] + [schema()["adr_id"]]
    return re.compile(r"\b(" + "|".join(pats) + r")\b")


def adr_id(path: Path) -> str | None:
    m = re.match(schema()["adr_id"], path.name)
    return m.group(0) if m else None


def rel(path: Path | str) -> str:
    p = Path(path)
    if not p.is_absolute():
        p = REPO / p
    return p.resolve().relative_to(REPO).as_posix()


def area_for(relpath: str) -> dict:
    for area in schema()["areas"]:
        if relpath.startswith(area["prefix"]):
            return area
    return {}


def top(relpath: str) -> str:
    return relpath.split("/", 1)[0]


def iter_md() -> list[Path]:
    out = []
    for root in MD_ROOTS:
        for p in sorted((REPO / root).rglob("*.md")):
            r = rel(p)
            if not r.startswith(SKIP_PREFIXES):
                out.append(p)
    return out


# ---------------------------------------------------------------- frontmatter


def split_frontmatter(text: str) -> tuple[dict, int]:
    """Return (fields, body_start_line). Tolerant: falls back to `key: value` lines."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, 0
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, 0
    raw = "\n".join(lines[1:end])
    try:
        data = yaml.safe_load(raw) or {}
        if not isinstance(data, dict):
            raise ValueError
    except Exception:  # noqa: BLE001 - malformed YAML is reported by the lint, not fatal
        data = {}
        for line in lines[1:end]:
            if ":" in line and not line.startswith((" ", "\t", "-")):
                k, v = line.split(":", 1)
                data[k.strip()] = v.strip()
    return {str(k): v for k, v in data.items()}, end + 1


def read_fm(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    return split_frontmatter(text)[0], text


def _fmt(value) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(_fmt(v) for v in value) + "]"
    s = str(value)
    if s == "" or re.search(r"[:#\[\]{}&*!|>'\"%@`]|^\s|\s$|^-", s):
        return json.dumps(s, ensure_ascii=False)
    return s


def set_fields(text: str, updates: dict, remove: tuple = ()) -> str:
    """Rewrite frontmatter keys line by line, preserving order, comments and the body."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        block = "".join(f"{k}: {_fmt(v)}\n" for k, v in updates.items())
        return f"---\n{block}---\n\n{text}"
    end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    pending = dict(updates)
    out = [lines[0]]
    i = 1
    while i < end:
        line = lines[i]
        key = line.split(":", 1)[0].strip() if ":" in line and not line[0].isspace() else None
        # swallow continuation lines (block lists) belonging to a key we rewrite/remove
        j = i + 1
        while j < end and (lines[j].startswith((" ", "\t")) or lines[j].lstrip().startswith("- ")):
            j += 1
        if key in pending:
            out.append(f"{key}: {_fmt(pending.pop(key))}\n")
        elif key in remove:
            pass
        else:
            out.extend(lines[i:j])
        i = j
    out.extend(f"{k}: {_fmt(v)}\n" for k, v in pending.items())
    out.extend(lines[end:])
    return "".join(out)


def evidence_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(v).strip() for v in value]
    return [str(value).strip()]


def evidence_rank(level: str) -> int:
    """0 = strongest. Unknown levels rank weakest."""
    levels = schema()["evidence"]
    return levels.index(level) if level in levels else len(levels)


def strongest(levels: list[str]) -> str | None:
    known = [lv for lv in levels if lv in schema()["evidence"]]
    return min(known, key=evidence_rank) if known else None


def weakest(levels: list[str]) -> str | None:
    known = [lv for lv in levels if lv in schema()["evidence"]]
    return max(known, key=evidence_rank) if known else None


# ---------------------------------------------------------------- yaml io


def load_yaml(path: Path) -> dict:
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


class _Dumper(yaml.SafeDumper):
    pass


def _str_rep(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_rep)


def dump_yaml(data, path: Path) -> None:
    path.write_text(
        yaml.dump(data, Dumper=_Dumper, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8",
    )
